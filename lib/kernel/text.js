/**
 * 文本原语：把**任意字符串**安全地嵌进 `new RegExp(...)`。
 *
 * ## 为什么它必须只有一份
 *
 * 这个函数原来在 `lib/anchor.js` 与 `lib/drift.js` 各有一份**逐字节相同**的
 * 复制品。用途也相同：把符号名（`createPool`、`parse_file`、`$scope`）
 * 嵌进正则去搜定义处。所以这里没有「两种语义各有道理」的借口 ——
 * 复制品就是漂移的起点：
 *
 * 某天有人只在一处补了 `-` / `/` 之类的字符类（符号名里确实可能有），
 * 另一处就开始把带特殊字符的名字当**模式**跑 —— `a.b` 会匹配 `axb`，
 * 一个只出现在注释里的名字于是被当成「定义处还在」，漂移检测永远报 healthy。
 * 而**没有任何测试会红**：两份实现的值在常规符号名上完全一样。
 *
 * ## 为什么要转义全部这些字符
 *
 * 这是 JS 正则里**在字符类之外**有特殊含义的那一组，一个不多一个不少：
 *
 *   `.*+?^${}()|[]\`
 *
 * 少的后果是「本该是字面量的字符变成通配符」（漏报），多的后果是「合法的
 * 符号名被转义成另一个模式」（误报）。两边都是错的，所以这个集合不是
 * 随手写的，别为了「看起来更安全」加 `-/~` 之类的字符。
 *
 * **不做 `String()` 兜底**是刻意的：两个调用方都保证传字符串（`anchor.js` 的
 * `findDefinition` 已经 `String(name ?? '')`，`drift.js` 的 `name` 来自解析
 * 后的锚点）。在这里静默 `String(undefined)` 会造出 `"undefined"` 这个
 * **会被匹配到的 token** —— `lifecycle.js` 的 `proposeOrphans` 记着同款教训：
 * 凭空造出的字面量词会让两条毫不相关的记忆「共享一个 token」。
 *
 * @param {string} text 要转义的原文
 * @returns {string}
 */
export function escapeRegex(text) {
  return text.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
}
